#!/usr/bin/env bash
# Regenerate the locally maintained operator + CRD chart sources from the
# official OpenShift GitOps 1.22.2 operator bundle, then package both charts
# into deterministic archives under ../charts/.
#
# This is a MAINTAINER tool. It is not needed to render (render.sh consumes
# the committed, checksum-pinned archives). It needs a locally extracted copy
# of the official bundle layer (see PROVENANCE.md) and only trusts files whose
# SHA256 matches upstream.sha256; it never fetches anything.
#
# Usage: build-charts.sh --bundle-dir <dir containing manifests/>
set -euo pipefail

die() { echo "build-charts.sh: $*" >&2; exit 1; }

BUNDLE_DIR=""
while [[ $# -gt 0 ]]; do
  case "$1" in
    --bundle-dir) BUNDLE_DIR="$2"; shift 2 ;;
    *) die "unknown argument: $1" ;;
  esac
done
[[ -d "$BUNDLE_DIR/manifests" ]] || die "--bundle-dir must contain manifests/"

for t in yq jq python3 shasum; do command -v "$t" >/dev/null || die "missing tool: $t"; done

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TOOL_DIR="$(dirname "$HERE")"
CSV_NAME="gitops-operator.clusterserviceversion.yaml"

# Only trust bundle files that match the recorded official digests.
while read -r sum path; do
  actual="$(shasum -a 256 "$BUNDLE_DIR/$path" | awk '{print $1}')"
  [[ "$actual" == "$sum" ]] || die "bundle file does not match upstream.sha256: $path"
done < "$HERE/upstream.sha256"
cmp -s "$BUNDLE_DIR/manifests/$CSV_NAME" "$HERE/upstream/gitops-operator.v1.22.2.clusterserviceversion.yaml" \
  || die "vendored CSV copy differs from the verified bundle CSV"

CRD_DIR="$HERE/gitops-operator-crds/crds"
mkdir -p "$CRD_DIR"
rm -f "$CRD_DIR"/*.yaml

# Eight CRDs only: the three Application CRDs (published as a separate
# artifact for the parent), plus the four operator-required schemas and the
# ControllerConfiguration dependency seed. See PROVENANCE.md.
for f in argoproj.io_applications.yaml argoproj.io_applicationsets.yaml argoproj.io_appprojects.yaml \
         argoproj.io_rolloutmanagers.yaml argoproj.io_namespacemanagements.yaml \
         argoproj.io_notificationsconfigurations.yaml promoter.argoproj.io_controllerconfigurations.yaml; do
  name="$(yq eval '.spec.names.plural + "." + .spec.group' "$BUNDLE_DIR/manifests/$f")"
  cp "$BUNDLE_DIR/manifests/$f" "$CRD_DIR/$name.yaml"
done

# The single documented adaptation: ArgoCD is v1beta1-only with no conversion
# webhook, because this packaging never enables the conversion webhook (no
# serving certificates). The v1beta1 version block is unchanged; the test
# suite asserts that. v1alpha1 (served, deprecated, non-storage) and
# spec.conversion are removed.
yq eval 'del(.spec.versions[] | select(.name == "v1alpha1")) | del(.spec.conversion)' \
  "$BUNDLE_DIR/manifests/argoproj.io_argocds.yaml" > "$CRD_DIR/argocds.argoproj.io.yaml"

# ---- operator chart: values and RBAC generated from the official CSV ----
CSV_JSON="$(yq eval -o=json -I=0 '.' "$BUNDLE_DIR/manifests/$CSV_NAME")"
MANAGER_IMAGE="$(jq -er '.spec.install.spec.deployments[0].spec.template.spec.containers[] | select(.name=="manager") | .image' <<<"$CSV_JSON")"

{
  cat <<'EOF'
# GENERATED by chart-src/build-charts.sh from the official OpenShift GitOps
# 1.22.2 bundle CSV (see ../PROVENANCE.md). Do not edit by hand.
#
# `env` and `imageEnv` replicate the official manager container env. Image
# values are the official digest-pinned references; there is no floating tag
# and no fallback. ENABLE_CONVERSION_WEBHOOK defaults to "false" (official
# CSV default is "true"): this packaging ships the v1beta1-only ArgoCD CRD
# and no serving certificates, so enabling conversion is rejected at render
# time. WATCH_NAMESPACE is set to "" (OLM injects this for AllNamespaces).
#
# `resources` is an UNTUNED INITIAL BUDGET added by this packaging (the official
# CSV sets `resources: {}`). It has no performance or sizing guarantee and no
# verified source: it must be validated against observed manager
# startup/reconcile CPU and memory, throttling, OOM kills and restarts before
# activation or promotion (see bootstrap-gitops/README.md).
replicaCount: 1
serviceAccount:
  name: openshift-gitops-operator-controller-manager
# Never rendered by this chart; accepted only because render.sh always sets it.
pullSecret:
  create: false
imagePullSecrets: []
EOF
  jq -n --arg image "$MANAGER_IMAGE" '{image: {manager: $image}}' | yq eval -P '.' -
  jq -n '{resources: {requests: {cpu: "100m", memory: "256Mi"}, limits: {cpu: "1", memory: "1Gi"}}}' | yq eval -P '.' -
  jq -c '
    .spec.install.spec.deployments[0].spec.template.spec.containers[] | select(.name=="manager") | .env
    | map(select(.name | test("IMAGE") | not))
    | map({(.name): (.value // "")}) | add
    | .ENABLE_CONVERSION_WEBHOOK = "false"
    | .WATCH_NAMESPACE = ""
    | {env: .}' <<<"$CSV_JSON" | yq eval -P '.' -
  jq -c '
    .spec.install.spec.deployments[0].spec.template.spec.containers[] | select(.name=="manager") | .env
    | map(select(.name | test("IMAGE")))
    | map({(.name): .value}) | add | {imageEnv: .}' <<<"$CSV_JSON" | yq eval -P '.' -
} > "$HERE/gitops-operator/values.yaml"

gen_rules() {
  # $1 = jq path to a rules array in the CSV
  jq -c "$1" <<<"$CSV_JSON" | yq eval -P '.' - | sed 's/^/  /'
}
{
  cat <<'EOF'
# GENERATED by chart-src/build-charts.sh from the official CSV
# (spec.install.spec.clusterPermissions[0].rules and permissions[0].rules).
# Do not edit by hand.
apiVersion: rbac.authorization.k8s.io/v1
kind: ClusterRole
metadata:
  name: openshift-gitops-operator-controller-manager
rules:
EOF
  gen_rules '.spec.install.spec.clusterPermissions[0].rules'
  cat <<'EOF'
---
apiVersion: rbac.authorization.k8s.io/v1
kind: ClusterRoleBinding
metadata:
  name: openshift-gitops-operator-controller-manager
roleRef:
  apiGroup: rbac.authorization.k8s.io
  kind: ClusterRole
  name: openshift-gitops-operator-controller-manager
subjects:
  - kind: ServiceAccount
    name: {{ include "gitops-operator.serviceAccountName" . }}
    namespace: {{ .Release.Namespace }}
---
apiVersion: rbac.authorization.k8s.io/v1
kind: Role
metadata:
  name: openshift-gitops-operator-leader-election
  namespace: {{ .Release.Namespace }}
rules:
EOF
  gen_rules '.spec.install.spec.permissions[0].rules'
  cat <<'EOF'
---
apiVersion: rbac.authorization.k8s.io/v1
kind: RoleBinding
metadata:
  name: openshift-gitops-operator-leader-election
  namespace: {{ .Release.Namespace }}
roleRef:
  apiGroup: rbac.authorization.k8s.io
  kind: Role
  name: openshift-gitops-operator-leader-election
subjects:
  - kind: ServiceAccount
    name: {{ include "gitops-operator.serviceAccountName" . }}
    namespace: {{ .Release.Namespace }}
EOF
} > "$HERE/gitops-operator/templates/rbac.yaml"

# Reviewed image allowlist = every distinct relatedImages ref in the CSV.
{
  cat <<'EOF'
# Reviewed image allowlist for OpenShift GitOps 1.22.2 (official bundle
# registry.redhat.io/openshift-gitops-1/gitops-operator-bundle@sha256:2ba58c50f771c08bbc5a1d8572c7b058df55bc71667cc66026d42840eb4bee6d).
# GENERATED by chart-src/build-charts.sh: the distinct spec.relatedImages
# references of the official CSV. Public-catalog presence of each digest is
# recorded in chart-src/PROVENANCE.md. This is engineering pin resolution,
# not a support or certification claim (GCP-1286).
EOF
  jq -r '.spec.relatedImages[].image' <<<"$CSV_JSON" | sort -u
} > "$TOOL_DIR/allowed-images.txt"

for c in gitops-operator gitops-operator-crds; do
  cp "$HERE/LICENSE-gitops-operator.Apache-2.0" "$HERE/$c/LICENSE"
  cp "$HERE/NOTICE" "$HERE/$c/NOTICE"
done

mkdir -p "$TOOL_DIR/charts"
python3 -I "$HERE/package-chart.py" "$HERE/gitops-operator-crds" "$TOOL_DIR/charts"
python3 -I "$HERE/package-chart.py" "$HERE/gitops-operator" "$TOOL_DIR/charts"
# The generated CRD sources are intentionally not committed (the pinned archive
# is the vendored artifact; ~7 MB of generated YAML would only duplicate it).
# Record their digests so the archive contents stay auditable.
( cd "$HERE/gitops-operator-crds" && for f in crds/*.yaml; do echo "$(shasum -a 256 "$f" | awk '{print $1}')  $f"; done ) > "$HERE/vendored-crds.sha256"
rm -f "$CRD_DIR"/*.yaml
shasum -a 256 "$TOOL_DIR"/charts/*.tgz
